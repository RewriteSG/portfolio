  /* -------------------- helpers -------------------- */

  function escapeHtml(str) {
    return String(str == null ? '' : str).replace(/[&<>"']/g, function (c) {
      return { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c];
    });
  }

  function fetchManifest() {
    return fetch('./projects.json', { cache: 'no-store' }).then(function (res) {
      if (!res.ok) throw new Error('HTTP ' + res.status);
      return res.json();
    });
  }

  function sortProjects(projects) {
    return projects.slice().sort(function (a, b) {
      var orderA = typeof a.order === 'number' ? a.order : -Infinity;
      var orderB = typeof b.order === 'number' ? b.order : -Infinity;
      if (orderA !== orderB) return orderB - orderA;
      var dateA = a.date ? Date.parse(a.date) : 0;
      var dateB = b.date ? Date.parse(b.date) : 0;
      return dateB - dateA;
    });
  }

  function mediaUrl(project, src) {
    if (/^https?:\/\//i.test(src)) return src;
    return './projects/' + project.id + '/' + src.replace(/^\.\//, '');
  }

  // A "direct" video is a file the browser can play natively via <video>
  // (mp4/webm/ogg/mov) — whether that's a relative repo path or an
  // externally-hosted file link. Anything else that's an http(s) URL
  // (YouTube, Vimeo, itch.io, ...) is treated as an iframe embed.
  function isDirectVideoFile(src) { return /\.(mp4|webm|ogv|ogg|mov)(\?.*)?$/i.test(src); }
  function isIframeEmbed(src) { return /^https?:\/\//i.test(src) && !isDirectVideoFile(src); }
  function isVideoEmbed(src) { return isIframeEmbed(src); } // back-compat alias

  // Appends provider-specific autoplay/mute query params so an iframe embed
  // actually autoplays — browsers require muted for unattended autoplay.
  function withAutoplayParams(src) {
    var sep = src.indexOf('?') !== -1 ? '&' : '?';
    if (/(^https?:\/\/)(www\.)?(youtube\.com\/embed\/|youtu\.be\/)/i.test(src)) {
      return src + sep + 'autoplay=1&mute=1&playsinline=1';
    }
    if (/player\.vimeo\.com/i.test(src)) {
      return src + sep + 'autoplay=1&muted=1';
    }
    // Unknown provider (itch.io, a custom embed, etc.) — leave untouched;
    // most non-video-platform embeds don't support/need these params.
    return src;
  }

  function thumbUrl(p) {
    return p.thumbnail ? mediaUrl(p, p.thumbnail) : null;
  }

  function truncate(str, n) {
    str = str || '';
    return str.length > n ? str.slice(0, n - 1).trim() + '…' : str;
  }

  function tagLabelFor(p) { return (p.tags && p.tags[0]) ? p.tags[0] : 'project'; }
  function codeFor(p) { return p.code || (p.tags && p.tags[1]) || (p.tags && p.tags[0]) || ''; }
  function yearFor(p) { return p.date ? p.date.slice(0, 4) : ''; }
  function mediaFor(p) {
    return (p.media && p.media.length) ? p.media : (p.thumbnail ? [{ type: 'image', src: p.thumbnail }] : []);
  }
  function commitsFor(p) {
    if (p.commits && p.commits.length) return p.commits;
    var lines = [];
    if (p.status) lines.push('status: ' + p.status);
    if (p.tags && p.tags.length) lines.push('tags: ' + p.tags.join(', '));
    if (p.date) lines.push('last_touched: ' + p.date);
    if (!lines.length) lines.push('no history recorded yet');
    return lines;
  }

  /* -------------------- WebGL background shader -------------------- */

  var gl, glProg, uT, uR, uC, raf;

  function setupShader() {
    var canvas = document.getElementById('bg-canvas');
    if (!canvas) return;
    canvas.width = 160;
    canvas.height = 90;
    try { gl = canvas.getContext('webgl'); } catch (e) { gl = null; }
    if (!gl) return;

    var vs = 'attribute vec2 p; void main(){ gl_Position = vec4(p,0.0,1.0); }';
    var fs = 'precision mediump float; uniform float uT; uniform vec2 uR; uniform vec3 uC;\n' +
      'void main(){\n' +
      '  vec2 uv = gl_FragCoord.xy / uR;\n' +
      '  float v = sin(uv.x*3.0+uT*0.12) + sin(uv.y*3.6-uT*0.1) + sin((uv.x+uv.y)*4.2+uT*0.08)\n' +
      '    + sin(sqrt((uv.x-0.5)*(uv.x-0.5)+(uv.y-0.5)*(uv.y-0.5))*7.0-uT*0.15);\n' +
      '  v = v*0.25+0.5;\n' +
      '  gl_FragColor = vec4(uC*v, 1.0);\n' +
      '}';
    function compile(type, src) { var s = gl.createShader(type); gl.shaderSource(s, src); gl.compileShader(s); return s; }
    glProg = gl.createProgram();
    gl.attachShader(glProg, compile(gl.VERTEX_SHADER, vs));
    gl.attachShader(glProg, compile(gl.FRAGMENT_SHADER, fs));
    gl.linkProgram(glProg);
    gl.useProgram(glProg);
    var buf = gl.createBuffer();
    gl.bindBuffer(gl.ARRAY_BUFFER, buf);
    gl.bufferData(gl.ARRAY_BUFFER, new Float32Array([-1, -1, 1, -1, -1, 1, 1, 1]), gl.STATIC_DRAW);
    var loc = gl.getAttribLocation(glProg, 'p');
    gl.enableVertexAttribArray(loc);
    gl.vertexAttribPointer(loc, 2, gl.FLOAT, false, 0, 0);
    uT = gl.getUniformLocation(glProg, 'uT');
    uR = gl.getUniformLocation(glProg, 'uR');
    uC = gl.getUniformLocation(glProg, 'uC');
    gl.uniform2f(uR, canvas.width, canvas.height);

    function hexToRgb(hex) {
      var n = parseInt(hex.slice(1), 16);
      return [((n >> 16) & 255) / 255, ((n >> 8) & 255) / 255, (n & 255) / 255];
    }
    function tick(t) {
      if (!gl) return;
      var rgb = hexToRgb(ACCENTS[state.accent] || ACCENTS.green);
      gl.uniform1f(uT, t / 1000);
      gl.uniform3f(uC, rgb[0], rgb[1], rgb[2]);
      gl.viewport(0, 0, canvas.width, canvas.height);
      gl.drawArrays(gl.TRIANGLE_STRIP, 0, 4);
      raf = requestAnimationFrame(tick);
    }
    raf = requestAnimationFrame(tick);
  }

