/* ============================================================
   Portfolio front-end — vanilla JS, no build step.
   Single-page app: fetches ./projects.json (generated by the
   GitHub Action) and renders home / work / about / contact /
   project-detail views client-side, with a CRT boot intro,
   animated WebGL background, typing effects, an accent-color
   toggle, and an image lightbox.
   ============================================================ */

