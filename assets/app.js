/* ============================================================
   Portfolio front-end — vanilla JS, no build step.
   Fetches ./projects.json (generated by the GitHub Action) and
   renders either the project grid (index.html) or a project
   detail view (project.html).
   ============================================================ */

(function () {
  'use strict';

  function escapeHtml(str) {
    return String(str == null ? '' : str).replace(/[&<>"']/g, function (c) {
      return { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c];
    });
  }

  function fetchManifest() {
    return fetch('./projects.json', { cache: 'no-store' }).then(function (res) {
      if (!res.ok) throw new Error('HTTP ' + res.status);
      return res.json();
    });
  }

  function sortProjects(projects) {
    return projects.slice().sort(function (a, b) {
      var orderA = typeof a.order === 'number' ? a.order : -Infinity;
      var orderB = typeof b.order === 'number' ? b.order : -Infinity;
      if (orderA !== orderB) return orderB - orderA;
      var dateA = a.date ? Date.parse(a.date) : 0;
      var dateB = b.date ? Date.parse(b.date) : 0;
      return dateB - dateA;
    });
  }

  function statusBadge(status) {
    if (status === 'in-progress') return '<span class="badge badge-status">in progress</span>';
    if (status === 'prototype') return '<span class="badge badge-status">prototype</span>';
    return '';
  }

  /* -------------------- index.html grid -------------------- */

  function initGrid() {
    var grid = document.getElementById('grid');
    var filtersEl = document.getElementById('filters');
    if (!grid) return;

    fetchManifest().then(function (manifest) {
      var projects = sortProjects(manifest.projects || []);

      if (!projects.length) {
        grid.innerHTML = '<div class="state-box">No projects yet. Add one under <code>projects/</code> and push to main.</div>';
        return;
      }

      // stats
      var years = document.getElementById('stat-years');
      var projCount = document.getElementById('stat-projects');
      var disciplines = document.getElementById('stat-disciplines');
      var wip = document.getElementById('stat-wip');
      if (projCount) projCount.textContent = String(projects.length).padStart(2, '0');
      if (disciplines) {
        var tagSet = new Set();
        projects.forEach(function (p) { (p.tags || []).forEach(function (t) { tagSet.add(t); }); });
        disciplines.textContent = String(tagSet.size).padStart(2, '0');
      }
      if (wip) {
        var wipCount = projects.filter(function (p) { return p.status === 'in-progress' || p.status === 'prototype'; }).length;
        wip.textContent = String(wipCount).padStart(2, '0');
      }
      if (years) {
        var earliest = projects.reduce(function (min, p) {
          var t = p.date ? Date.parse(p.date) : NaN;
          return isNaN(t) ? min : Math.min(min, t);
        }, Date.now());
        var span = Math.max(0, Math.round((Date.now() - earliest) / (365.25 * 24 * 3600 * 1000)));
        years.textContent = String(span).padStart(2, '0');
      }

      // tag filters
      var allTags = [];
      projects.forEach(function (p) { (p.tags || []).forEach(function (t) { if (allTags.indexOf(t) === -1) allTags.push(t); }); });

      var activeTag = null;

      function renderFilters() {
        if (!filtersEl) return;
        var html = '<button class="pill' + (activeTag === null ? ' active' : '') + '" data-tag="">all</button>';
        allTags.forEach(function (t) {
          html += '<button class="pill' + (activeTag === t ? ' active' : '') + '" data-tag="' + escapeHtml(t) + '">' + escapeHtml(t) + '</button>';
        });
        filtersEl.innerHTML = html;
        Array.prototype.forEach.call(filtersEl.querySelectorAll('.pill'), function (btn) {
          btn.addEventListener('click', function () {
            activeTag = btn.getAttribute('data-tag') || null;
            renderFilters();
            renderGrid();
          });
        });
      }

      function renderGrid() {
        var list = activeTag ? projects.filter(function (p) { return (p.tags || []).indexOf(activeTag) !== -1; }) : projects;
        if (!list.length) {
          grid.innerHTML = '<div class="state-box">No projects match this filter.</div>';
          return;
        }
        grid.innerHTML = list.map(function (p) {
          var thumb = p.thumbnail
            ? '<img src="' + escapeHtml('./projects/' + p.id + '/' + p.thumbnail.replace(/^\.\//, '')) + '" alt="' + escapeHtml(p.name) + ' thumbnail" loading="lazy">'
            : '<div class="card-thumb-empty">no preview</div>';
          var tag = (p.tags && p.tags[0]) ? escapeHtml(p.tags[0].toUpperCase()) : '';
          return (
            '<a class="card" href="./project.html?id=' + encodeURIComponent(p.id) + '">' +
              statusBadge(p.status) +
              '<div class="card-thumb-wrap">' + thumb + '</div>' +
              (tag ? '<span class="badge">' + tag + '</span>' : '') +
              '<h3>' + escapeHtml(p.name) + '</h3>' +
              '<p>' + escapeHtml(p.description || '') + '</p>' +
              '<div class="meta">' + escapeHtml((p.tags || []).join(' · ')) + (p.date ? ' · ' + escapeHtml(p.date.slice(0, 4)) : '') + '</div>' +
            '</a>'
          );
        }).join('');
      }

      renderFilters();
      renderGrid();
    }).catch(function (err) {
      grid.innerHTML = '<div class="state-box error">Failed to load projects.json — ' + escapeHtml(err.message) + '</div>';
    });
  }

  /* -------------------- project.html detail -------------------- */

  function initDetail() {
    var root = document.getElementById('detail-root');
    if (!root) return;

    var params = new URLSearchParams(window.location.search);
    var id = params.get('id');

    if (!id) {
      root.innerHTML = notFoundHtml();
      return;
    }

    fetchManifest().then(function (manifest) {
      var project = (manifest.projects || []).find(function (p) { return p.id === id; });
      if (!project) {
        root.innerHTML = notFoundHtml();
        return;
      }
      document.title = project.name + ' — A.Voss';
      root.innerHTML = detailHtml(project);
      wireGallery(project);
    }).catch(function (err) {
      root.innerHTML = '<div class="state-box error">Failed to load projects.json — ' + escapeHtml(err.message) + '</div>';
    });
  }

  function notFoundHtml() {
    return (
      '<div class="notfound page">' +
        '<div class="prompt">&gt; cat: not_found</div>' +
        '<h1 class="glow-heading">404 — project not found</h1>' +
        '<p class="lede" style="margin: 20px auto 30px;">This project doesn\'t exist, or was removed.</p>' +
        '<a class="btn btn-outline" href="./index.html">&lt; back to work</a>' +
      '</div>'
    );
  }

  function mediaUrl(project, src) {
    if (/^https?:\/\//i.test(src)) return src;
    return './projects/' + project.id + '/' + src.replace(/^\.\//, '');
  }

  function isVideoEmbed(src) {
    return /^https?:\/\//i.test(src);
  }

  function detailHtml(project) {
    var media = project.media && project.media.length ? project.media : (project.thumbnail ? [{ type: 'image', src: project.thumbnail }] : []);
    var links = project.links || {};
    var linkEntries = Object.keys(links).map(function (key) {
      return '<a href="' + escapeHtml(links[key]) + '" target="_blank" rel="noopener">$ open ' + escapeHtml(key) + '</a>';
    });

    var firstMedia = media[0];
    var galleryInner = firstMedia ? mediaHtml(project, firstMedia, 0) : '<div class="gallery-empty">no media yet</div>';

    return (
      '<div class="page">' +
        '<a class="back-link" href="./index.html">&lt; back to work</a>' +
        '<div class="prompt">&gt; cat ' + escapeHtml(project.id.toLowerCase()) + '/readme</div>' +
        '<h1 class="glow-heading">' + escapeHtml(project.name) + '</h1>' +
        '<div class="detail-badges">' +
          (project.tags || []).map(function (t) { return '<span class="badge">' + escapeHtml(t.toUpperCase()) + '</span>'; }).join('') +
          (project.date ? '<span class="detail-meta">' + escapeHtml(project.date) + '</span>' : '') +
        '</div>' +

        '<div class="detail-grid">' +
          '<div>' +
            '<div class="gallery" id="gallery" data-index="0">' +
              (media.length > 1 ? '<div class="gallery-nav prev" id="gal-prev">&lsaquo;</div>' : '') +
              galleryInner +
              (media.length > 1 ? '<div class="gallery-nav next" id="gal-next">&rsaquo;</div>' : '') +
              (media.length > 1 ? '<div class="gallery-counter" id="gal-counter">01 / ' + String(media.length).padStart(2, '0') + '</div>' : '') +
            '</div>' +
            '<div class="gallery-caption" id="gal-caption">' + escapeHtml(firstMedia && firstMedia.caption || '') + '</div>' +
          '</div>' +
          '<div class="detail-desc">' +
            '<h2>' + escapeHtml(project.description || '') + '</h2>' +
          '</div>' +
        '</div>' +

        '<div class="section-split">' +
          '<div>' +
            '<div class="section-label">tags/</div>' +
            '<div class="tag-row">' + (project.tags || []).map(function (t) { return '<span class="badge">' + escapeHtml(t) + '</span>'; }).join('') + '</div>' +
          '</div>' +
          '<div>' +
            '<div class="section-label">links/</div>' +
            '<div class="links-list">' + (linkEntries.length ? linkEntries.join('') : '<span class="detail-meta">no links yet</span>') + '</div>' +
          '</div>' +
        '</div>' +
      '</div>' +

      '<div class="lightbox-overlay" id="lightbox">' +
        '<div class="lightbox-close" id="lb-close">&times;</div>' +
        (media.length > 1 ? '<div class="lightbox-arrow prev" id="lb-prev">&lsaquo;</div>' : '') +
        '<img id="lb-img" src="" alt="">' +
        (media.length > 1 ? '<div class="lightbox-arrow next" id="lb-next">&rsaquo;</div>' : '') +
      '</div>'
    );
  }

  function mediaHtml(project, item, idx) {
    if (item.type === 'video') {
      var src = item.src;
      if (isVideoEmbed(src)) {
        return '<iframe src="' + escapeHtml(src) + '" allow="accelerometer; autoplay; clipboard-write; encrypted-media; gyroscope; picture-in-picture" allowfullscreen></iframe>';
      }
      return '<video src="' + escapeHtml(mediaUrl(project, src)) + '" controls></video>';
    }
    var url = mediaUrl(project, item.src);
    return '<img src="' + escapeHtml(url) + '" alt="' + escapeHtml(item.caption || project.name) + '" data-lightbox-src="' + escapeHtml(url) + '">';
  }

  function wireGallery(project) {
    var media = project.media && project.media.length ? project.media : (project.thumbnail ? [{ type: 'image', src: project.thumbnail }] : []);
    if (!media.length) return;

    var gallery = document.getElementById('gallery');
    var counter = document.getElementById('gal-counter');
    var caption = document.getElementById('gal-caption');
    var prevBtn = document.getElementById('gal-prev');
    var nextBtn = document.getElementById('gal-next');
    var index = 0;

    function render() {
      gallery.querySelectorAll(':scope > img, :scope > video, :scope > iframe').forEach(function (el) { el.remove(); });
      var html = mediaHtml(project, media[index], index);
      var wrapper = document.createElement('div');
      wrapper.innerHTML = html;
      var el = wrapper.firstChild;
      if (prevBtn) gallery.insertBefore(el, prevBtn.nextSibling);
      else gallery.insertBefore(el, gallery.firstChild);
      if (counter) counter.textContent = String(index + 1).padStart(2, '0') + ' / ' + String(media.length).padStart(2, '0');
      if (caption) caption.textContent = media[index].caption || '';
    }

    if (prevBtn) prevBtn.addEventListener('click', function () { index = (index - 1 + media.length) % media.length; render(); });
    if (nextBtn) nextBtn.addEventListener('click', function () { index = (index + 1) % media.length; render(); });

    // lightbox
    var lightbox = document.getElementById('lightbox');
    var lbImg = document.getElementById('lb-img');
    var lbClose = document.getElementById('lb-close');
    var lbPrev = document.getElementById('lb-prev');
    var lbNext = document.getElementById('lb-next');

    function imageIndices() {
      var out = [];
      media.forEach(function (m, i) { if (m.type !== 'video') out.push(i); });
      return out;
    }

    function openLightbox(i) {
      index = i;
      render();
      var item = media[i];
      if (item.type === 'video') return;
      lbImg.src = mediaUrl(project, item.src);
      lightbox.classList.add('open');
    }

    function closeLightbox() { lightbox.classList.remove('open'); }

    gallery.addEventListener('click', function (e) {
      var target = e.target.closest('[data-lightbox-src]');
      if (target) openLightbox(index);
    });

    if (lbClose) lbClose.addEventListener('click', closeLightbox);
    if (lightbox) lightbox.addEventListener('click', function (e) { if (e.target === lightbox) closeLightbox(); });

    function stepLightbox(dir) {
      var imgs = imageIndices();
      if (!imgs.length) return;
      var pos = imgs.indexOf(index);
      pos = (pos + dir + imgs.length) % imgs.length;
      index = imgs[pos];
      render();
      lbImg.src = mediaUrl(project, media[index].src);
    }

    if (lbPrev) lbPrev.addEventListener('click', function () { stepLightbox(-1); });
    if (lbNext) lbNext.addEventListener('click', function () { stepLightbox(1); });

    document.addEventListener('keydown', function (e) {
      if (!lightbox.classList.contains('open')) return;
      if (e.key === 'Escape') closeLightbox();
      if (e.key === 'ArrowLeft') stepLightbox(-1);
      if (e.key === 'ArrowRight') stepLightbox(1);
    });

    render();
  }

  document.addEventListener('DOMContentLoaded', function () {
    initGrid();
    initDetail();
  });
})();
