/* ============================================================
   Portfolio front-end — vanilla JS, no build step.
   Single-page app: fetches ./projects.json (generated by the
   GitHub Action) and renders home / work / about / contact /
   project-detail views client-side, with a CRT boot intro,
   animated WebGL background, typing effects, an accent-color
   toggle, and an image lightbox.
   ============================================================ */

(function () {
  'use strict';

  var ACCENTS = { green: '#33ff99', amber: '#ffb000', cyan: '#4dd0ff' };
  var ACCENT_ORDER = ['green', 'amber', 'cyan'];

  var state = {
    projects: [],
    filter: null,
    page: 'home',
    activeId: null,
    mediaIndex: 0,
    accent: localStorage.getItem('accent') || 'green',
    introSeen: sessionStorage.getItem('introSeen') === '1'
  };

  /* -------------------- helpers -------------------- */

  function escapeHtml(str) {
    return String(str == null ? '' : str).replace(/[&<>"']/g, function (c) {
      return { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c];
    });
  }

  function fetchManifest() {
    return fetch('./projects.json', { cache: 'no-store' }).then(function (res) {
      if (!res.ok) throw new Error('HTTP ' + res.status);
      return res.json();
    });
  }

  function sortProjects(projects) {
    return projects.slice().sort(function (a, b) {
      var orderA = typeof a.order === 'number' ? a.order : -Infinity;
      var orderB = typeof b.order === 'number' ? b.order : -Infinity;
      if (orderA !== orderB) return orderB - orderA;
      var dateA = a.date ? Date.parse(a.date) : 0;
      var dateB = b.date ? Date.parse(b.date) : 0;
      return dateB - dateA;
    });
  }

  function mediaUrl(project, src) {
    if (/^https?:\/\//i.test(src)) return src;
    return './projects/' + project.id + '/' + src.replace(/^\.\//, '');
  }

  function isVideoEmbed(src) { return /^https?:\/\//i.test(src); }

  function thumbUrl(p) {
    return p.thumbnail ? mediaUrl(p, p.thumbnail) : null;
  }

  function truncate(str, n) {
    str = str || '';
    return str.length > n ? str.slice(0, n - 1).trim() + '…' : str;
  }

  function tagLabelFor(p) { return (p.tags && p.tags[0]) ? p.tags[0] : 'project'; }
  function codeFor(p) { return p.code || (p.tags && p.tags[1]) || (p.tags && p.tags[0]) || ''; }
  function yearFor(p) { return p.date ? p.date.slice(0, 4) : ''; }
  function mediaFor(p) {
    return (p.media && p.media.length) ? p.media : (p.thumbnail ? [{ type: 'image', src: p.thumbnail }] : []);
  }
  function commitsFor(p) {
    if (p.commits && p.commits.length) return p.commits;
    var lines = [];
    if (p.status) lines.push('status: ' + p.status);
    if (p.tags && p.tags.length) lines.push('tags: ' + p.tags.join(', '));
    if (p.date) lines.push('last_touched: ' + p.date);
    if (!lines.length) lines.push('no history recorded yet');
    return lines;
  }

  /* -------------------- WebGL background shader -------------------- */

  var gl, glProg, uT, uR, uC, raf;

  function setupShader() {
    var canvas = document.getElementById('bg-canvas');
    if (!canvas) return;
    canvas.width = 160;
    canvas.height = 90;
    try { gl = canvas.getContext('webgl'); } catch (e) { gl = null; }
    if (!gl) return;

    var vs = 'attribute vec2 p; void main(){ gl_Position = vec4(p,0.0,1.0); }';
    var fs = 'precision mediump float; uniform float uT; uniform vec2 uR; uniform vec3 uC;\n' +
      'void main(){\n' +
      '  vec2 uv = gl_FragCoord.xy / uR;\n' +
      '  float v = sin(uv.x*3.0+uT*0.12) + sin(uv.y*3.6-uT*0.1) + sin((uv.x+uv.y)*4.2+uT*0.08)\n' +
      '    + sin(sqrt((uv.x-0.5)*(uv.x-0.5)+(uv.y-0.5)*(uv.y-0.5))*7.0-uT*0.15);\n' +
      '  v = v*0.25+0.5;\n' +
      '  gl_FragColor = vec4(uC*v, 1.0);\n' +
      '}';
    function compile(type, src) { var s = gl.createShader(type); gl.shaderSource(s, src); gl.compileShader(s); return s; }
    glProg = gl.createProgram();
    gl.attachShader(glProg, compile(gl.VERTEX_SHADER, vs));
    gl.attachShader(glProg, compile(gl.FRAGMENT_SHADER, fs));
    gl.linkProgram(glProg);
    gl.useProgram(glProg);
    var buf = gl.createBuffer();
    gl.bindBuffer(gl.ARRAY_BUFFER, buf);
    gl.bufferData(gl.ARRAY_BUFFER, new Float32Array([-1, -1, 1, -1, -1, 1, 1, 1]), gl.STATIC_DRAW);
    var loc = gl.getAttribLocation(glProg, 'p');
    gl.enableVertexAttribArray(loc);
    gl.vertexAttribPointer(loc, 2, gl.FLOAT, false, 0, 0);
    uT = gl.getUniformLocation(glProg, 'uT');
    uR = gl.getUniformLocation(glProg, 'uR');
    uC = gl.getUniformLocation(glProg, 'uC');
    gl.uniform2f(uR, canvas.width, canvas.height);

    function hexToRgb(hex) {
      var n = parseInt(hex.slice(1), 16);
      return [((n >> 16) & 255) / 255, ((n >> 8) & 255) / 255, (n & 255) / 255];
    }
    function tick(t) {
      if (!gl) return;
      var rgb = hexToRgb(ACCENTS[state.accent] || ACCENTS.green);
      gl.uniform1f(uT, t / 1000);
      gl.uniform3f(uC, rgb[0], rgb[1], rgb[2]);
      gl.viewport(0, 0, canvas.width, canvas.height);
      gl.drawArrays(gl.TRIANGLE_STRIP, 0, 4);
      raf = requestAnimationFrame(tick);
    }
    raf = requestAnimationFrame(tick);
  }

  /* -------------------- accent toggle -------------------- */

  function applyAccent() {
    document.documentElement.style.setProperty('--acc', ACCENTS[state.accent] || ACCENTS.green);
    var btn = document.getElementById('accent-toggle');
    if (btn) btn.textContent = 'accent: ' + state.accent;
  }

  function cycleAccent() {
    var i = ACCENT_ORDER.indexOf(state.accent);
    state.accent = ACCENT_ORDER[(i + 1) % ACCENT_ORDER.length];
    localStorage.setItem('accent', state.accent);
    applyAccent();
  }

  /* -------------------- CRT boot intro -------------------- */

  function buildBootLog(projectIds) {
    var modules = ['nvme', 'usbcore', 'ext4', 'overlayfs', 'cgroup2', 'netfilter', 'tcp_bbr', 'af_packet', 'loop', 'dm_crypt',
      'zram', 'btrfs', 'squashfs', 'acpi_cpufreq', 'i2c_core', 'drm_kms', 'snd_hda', 'cpufreq_governor', 'vfat', 'tmpfs'];
    var services = ['network-manager', 'systemd-journald', 'dbus', 'ssh-agent', 'cron', 'avahi-daemon', 'polkit', 'udisks2',
      'power-profiles', 'bluetooth', 'display-manager', 'thermald', 'fwupd', 'timesyncd', 'resolved', 'logind'];
    var paths = ['/dev/sda1', '/dev/nvme0n1p2', '/home/avoss', '/var/cache', '/etc/portfolio.conf', '/usr/local/bin', '/tmp/build',
      '/opt/toolchain', '/srv/assets', '/mnt/backup'];
    var lines = ['$ boot avoss_os --profile=portfolio', '> initializing session...'];
    var addr = 0x7f000000;
    var count = 160;
    for (var i = 0; i < count; i++) {
      var roll = i % 5;
      if (roll === 0) lines.push('[  ' + (i * 0.0137).toFixed(6) + '] Loading module ' + modules[i % modules.length] + '... ok');
      else if (roll === 1) lines.push('> starting ' + services[i % services.length] + '.service... ok');
      else if (roll === 2) { addr += 0x1000 * ((i % 7) + 1); lines.push('[  ' + (i * 0.0137).toFixed(6) + '] mapped region 0x' + addr.toString(16) + ' (' + paths[i % paths.length] + ')'); }
      else if (roll === 3) lines.push('> fsck ' + paths[i % paths.length] + ': clean, ' + ((i * 37) % 900 + 100) + ' files, ' + ((i * 13) % 90 + 10) + '% used');
      else lines.push('[ok] ' + services[(i + 3) % services.length] + ' :: pid ' + (1000 + i) + ' :: 0.' + (i % 9) + 's');
    }
    lines.push('> checking kernel modules... ok', '> mounting /dev/portfolio...', '> verifying user credentials... ok',
      '> loading shell profile: avoss.zshrc', '> starting display server...', '> network: connected (eth0, 1000 Mb/s)',
      '> syncing clock...', '> mounting home directory... ok', '', 'projects/');
    projectIds.forEach(function (id, i) {
      lines.push((i === projectIds.length - 1 ? '└── ' : '├── ') + id + '/');
    });
    lines.push('', '> ' + projectIds.length + ' projects loaded, 0 errors', '> ready.');
    return lines;
  }

  function runIntro(projectIds, onDone) {
    var overlay = document.getElementById('intro-overlay');
    var vignette = document.getElementById('intro-vignette');
    var logEl = document.getElementById('intro-log');
    var enterBtn = document.getElementById('intro-enter');

    if (state.introSeen) {
      overlay.style.display = 'none';
      vignette.style.display = 'none';
      onDone();
      return;
    }

    overlay.style.display = 'flex';
    vignette.style.display = 'block';

    var lines = buildBootLog(projectIds);
    var i = 0;
    var buf = [];
    var timer = setInterval(function () {
      var step = 4;
      for (var k = 0; k < step && i < lines.length; k++, i++) buf.push(lines[i]);
      logEl.textContent = buf.join('\n');
      logEl.scrollTop = logEl.scrollHeight;
      if (i >= lines.length) clearInterval(timer);
    }, 16);

    function finish() {
      clearInterval(timer);
      overlay.style.display = 'none';
      vignette.style.display = 'none';
      sessionStorage.setItem('introSeen', '1');
      state.introSeen = true;
      enterBtn.removeEventListener('click', finish);
      onDone();
    }
    enterBtn.addEventListener('click', finish);
  }

  function replayIntro() {
    state.introSeen = false;
    sessionStorage.removeItem('introSeen');
    document.getElementById('intro-log').textContent = '';
    runIntro(state.projects.map(function (p) { return p.id; }), function () {
      navigate('#/');
    });
  }

  /* -------------------- typing effect -------------------- */

  function typeInto(el, text, speed, withCaret) {
    if (!el) return;
    var i = 0;
    var timer = setInterval(function () {
      i++;
      el.innerHTML = escapeHtml(text.slice(0, i)) + (withCaret ? '<span class="caret"></span>' : '');
      if (i >= text.length) clearInterval(timer);
    }, speed || 16);
  }

  function animatePromptAndHeading(promptSel, headingSel, promptText, headingText) {
    var promptLive = document.querySelector(promptSel);
    var headingLive = document.querySelector(headingSel);
    if (promptLive) typeInto(promptLive, promptText, 14, true);
    if (headingLive) typeInto(headingLive, headingText, 10, false);
  }

  /* -------------------- card rendering -------------------- */

  function statusBadge(status) {
    if (status === 'in-progress') return '<span class="term-tag status">in progress</span>';
    if (status === 'prototype') return '<span class="term-tag status">prototype</span>';
    return '';
  }

  function cardHtml(p) {
    var thumb = thumbUrl(p);
    var thumbHtml = thumb
      ? '<img src="' + escapeHtml(thumb) + '" alt="' + escapeHtml(p.name) + ' thumbnail" loading="lazy">'
      : '<div class="card-thumb-empty">no preview</div>';
    return (
      '<div class="term-card" data-nav="project" data-id="' + escapeHtml(p.id) + '">' +
        statusBadge(p.status) +
        '<div class="img-hover-wrap" data-preview="' + escapeHtml(p.id) + '">' +
          thumbHtml +
          '<div class="zoom-icon"><svg width="26" height="26" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round"><circle cx="11" cy="11" r="7"></circle><line x1="21" y1="21" x2="16.65" y2="16.65"></line></svg></div>' +
        '</div>' +
        '<span class="term-tag">' + escapeHtml(tagLabelFor(p)) + '</span>' +
        '<h3>' + escapeHtml(p.name) + '</h3>' +
        '<p class="blurb">' + escapeHtml(truncate(p.description, 120)) + '</p>' +
        '<p class="meta">' + escapeHtml(codeFor(p)) + ' · ' + escapeHtml(yearFor(p)) + '</p>' +
      '</div>'
    );
  }

  function wireGridDelegation(gridEl) {
    gridEl.addEventListener('click', function (e) {
      var previewEl = e.target.closest('[data-preview]');
      if (previewEl) {
        e.stopPropagation();
        openLightboxForProject(previewEl.getAttribute('data-preview'));
        return;
      }
      var cardEl = e.target.closest('[data-nav="project"]');
      if (cardEl) navigate('#/project/' + cardEl.getAttribute('data-id'));
    });
  }

  /* -------------------- page renderers -------------------- */

  function renderHome() {
    var projects = sortProjects(state.projects);

    var projCount = document.getElementById('stat-projects');
    var disciplines = document.getElementById('stat-disciplines');
    var wip = document.getElementById('stat-wip');
    var years = document.getElementById('stat-years');
    if (projCount) projCount.textContent = String(projects.length).padStart(2, '0');
    if (disciplines) {
      var tagSet = new Set();
      projects.forEach(function (p) { (p.tags || []).forEach(function (t) { tagSet.add(t); }); });
      disciplines.textContent = String(tagSet.size).padStart(2, '0');
    }
    if (wip) {
      var wipCount = projects.filter(function (p) { return p.status === 'in-progress' || p.status === 'prototype'; }).length;
      wip.textContent = String(wipCount).padStart(2, '0');
    }
    if (years) {
      var earliest = projects.reduce(function (min, p) {
        var t = p.date ? Date.parse(p.date) : NaN;
        return isNaN(t) ? min : Math.min(min, t);
      }, Date.now());
      var span = Math.max(0, Math.round((Date.now() - earliest) / (365.25 * 24 * 3600 * 1000)));
      years.textContent = String(span).padStart(2, '0');
    }

    var grid = document.getElementById('home-grid');
    var featured = projects.slice(0, 3);
    grid.innerHTML = featured.length
      ? featured.map(cardHtml).join('')
      : '<div class="state-box">No projects yet. Add one under <code>projects/</code> and push to main.</div>';

    animatePromptAndHeading('#home-prompt-live', '#home-title-live',
      '> whoami', 'Programmer, building across games, software, apps & the web.');
  }

  var allTagsCache = [];

  function renderWorkFilters() {
    var filtersEl = document.getElementById('work-filters');
    var html = '<button type="button" class="term-tag' + (state.filter === null ? ' solid' : '') + '" data-tag="">all</button>';
    allTagsCache.forEach(function (t) {
      html += '<button type="button" class="term-tag' + (state.filter === t ? ' solid' : '') + '" data-tag="' + escapeHtml(t) + '">' + escapeHtml(t) + '</button>';
    });
    filtersEl.innerHTML = html;
  }

  function renderWork() {
    var projects = sortProjects(state.projects);
    allTagsCache = [];
    projects.forEach(function (p) { (p.tags || []).forEach(function (t) { if (allTagsCache.indexOf(t) === -1) allTagsCache.push(t); }); });

    renderWorkFilters();

    var list = state.filter ? projects.filter(function (p) { return (p.tags || []).indexOf(state.filter) !== -1; }) : projects;
    var grid = document.getElementById('work-grid');
    grid.innerHTML = list.length ? list.map(cardHtml).join('') : '<div class="state-box">No projects match this filter.</div>';

    var countEl = document.getElementById('work-count');
    if (countEl) countEl.textContent = String(list.length).padStart(2, '0') + ' project' + (list.length === 1 ? '' : 's');

    animatePromptAndHeading('#page-work .prompt-block .live', '#page-work .glow-heading',
      '> ls work/', 'All work');
  }

  function renderDetail(id) {
    var p = state.projects.find(function (x) { return x.id === id; });
    if (!p) { showPage('404'); return; }
    state.activeId = id;
    state.mediaIndex = 0;

    document.title = p.name + ' — A.Voss';
    document.getElementById('detail-prompt-ghost').textContent = '> cat ' + p.id.toLowerCase() + '/readme';
    document.getElementById('detail-title').textContent = p.name;

    var badges = (p.tags || []).map(function (t) { return '<span class="term-tag">' + escapeHtml(t) + '</span>'; }).join('');
    if (p.date) badges += '<span class="detail-meta">' + escapeHtml(p.date) + '</span>';
    document.getElementById('detail-badges').innerHTML = badges;

    document.getElementById('detail-subhead').textContent = p.subhead || p.name;
    document.getElementById('detail-long').textContent = p.long || p.description || '';

    document.getElementById('detail-stack').innerHTML = (p.stack || p.tags || [])
      .map(function (s) { return '<span class="term-tag">' + escapeHtml(s) + '</span>'; }).join('');

    document.getElementById('detail-commits').innerHTML = commitsFor(p)
      .map(function (c) { return '<div><span class="dollar">$</span> ' + escapeHtml(c) + '</div>'; }).join('');

    var links = p.links || {};
    var linkEntries = Object.keys(links).map(function (key) {
      return '<a href="' + escapeHtml(links[key]) + '" target="_blank" rel="noopener">$ open ' + escapeHtml(key) + '</a>';
    });
    document.getElementById('detail-links').innerHTML = linkEntries.length ? linkEntries.join('') : '<span class="detail-meta">no links yet</span>';

    renderDetailMedia();

    animatePromptAndHeading('#detail-prompt-live', '#detail-title',
      '> cat ' + p.id.toLowerCase() + '/readme', p.name);
  }

  function renderDetailMedia() {
    var p = state.projects.find(function (x) { return x.id === state.activeId; });
    if (!p) return;
    var media = mediaFor(p);
    var slot = document.getElementById('detail-media-slot');
    var counter = document.getElementById('detail-media-counter');

    if (!media.length) {
      slot.innerHTML = '<div class="card-thumb-empty">no media yet</div>';
      counter.style.display = 'none';
      return;
    }
    var item = media[state.mediaIndex] || media[0];
    if (item.type === 'video') {
      if (isVideoEmbed(item.src)) {
        slot.innerHTML = '<iframe src="' + escapeHtml(item.src) + '" allow="accelerometer; autoplay; clipboard-write; encrypted-media; gyroscope; picture-in-picture" allowfullscreen style="width:100%;height:100%;border:none;"></iframe>';
      } else {
        slot.innerHTML = '<video src="' + escapeHtml(mediaUrl(p, item.src)) + '" controls style="width:100%;height:100%;"></video>';
      }
    } else {
      slot.innerHTML = '<img src="' + escapeHtml(mediaUrl(p, item.src)) + '" alt="' + escapeHtml(item.caption || p.name) + '" style="width:100%;height:100%;object-fit:cover;">';
    }
    if (media.length > 1) {
      counter.style.display = '';
      counter.textContent = String(state.mediaIndex + 1).padStart(2, '0') + ' / ' + String(media.length).padStart(2, '0');
    } else {
      counter.style.display = 'none';
    }
  }

  function stepDetailMedia(dir) {
    var p = state.projects.find(function (x) { return x.id === state.activeId; });
    if (!p) return;
    var media = mediaFor(p);
    if (!media.length) return;
    state.mediaIndex = (state.mediaIndex + dir + media.length) % media.length;
    renderDetailMedia();
  }

  function renderAbout() {
    animatePromptAndHeading('#page-about .prompt-block .live', '#page-about .glow-heading',
      '> cat about.sh', 'Ten years turning ideas into working software.');
  }

  function renderContact() {
    animatePromptAndHeading('#page-contact .prompt-block .live', '#page-contact .glow-heading',
      '> ./contact.sh --init', "Let's build something.");
  }

  /* -------------------- lightbox -------------------- */

  function openLightboxForProject(id) {
    var p = state.projects.find(function (x) { return x.id === id; });
    if (!p) return;
    var media = mediaFor(p).filter(function (m) { return m.type !== 'video'; });
    if (!media.length) return;
    openLightbox(p, media, 0);
  }

  var lbState = null;

  function openLightbox(p, media, idx) {
    lbState = { p: p, media: media, idx: idx };
    var lb = document.getElementById('lightbox');
    var img = document.getElementById('lb-img');
    var caption = document.getElementById('lb-caption');
    var prevBtn = document.getElementById('lb-prev');
    var nextBtn = document.getElementById('lb-next');
    img.src = mediaUrl(p, media[idx].src);
    img.alt = media[idx].caption || p.name;
    if (media.length > 1) {
      prevBtn.style.display = '';
      nextBtn.style.display = '';
    } else {
      prevBtn.style.display = 'none';
      nextBtn.style.display = 'none';
    }
    if (media[idx].caption) {
      caption.style.display = '';
      caption.textContent = media[idx].caption;
    } else {
      caption.style.display = 'none';
    }
    lb.classList.add('open');
  }

  function stepLightbox(dir) {
    if (!lbState) return;
    lbState.idx = (lbState.idx + dir + lbState.media.length) % lbState.media.length;
    openLightbox(lbState.p, lbState.media, lbState.idx);
  }

  function closeLightbox() {
    document.getElementById('lightbox').classList.remove('open');
    lbState = null;
  }

  /* -------------------- routing -------------------- */

  function showPage(name) {
    ['home', 'work', 'about', 'detail', 'contact', '404'].forEach(function (n) {
      var el = document.getElementById('page-' + n);
      if (el) el.style.display = n === name ? 'block' : 'none';
    });
    document.querySelectorAll('.term-tab').forEach(function (tab) {
      tab.classList.toggle('active', tab.getAttribute('data-page') === (name === 'detail' ? 'work' : name));
    });
    window.scrollTo({ top: 0, behavior: 'instant' in window ? 'instant' : 'auto' });
  }

  function router() {
    var hash = window.location.hash || '#/';
    var m;
    if (hash === '#/' || hash === '') {
      state.page = 'home';
      showPage('home');
      renderHome();
      document.title = 'A.Voss — Portfolio';
    } else if (hash === '#/work') {
      state.page = 'work';
      showPage('work');
      renderWork();
      document.title = 'Work — A.Voss';
    } else if (hash === '#/about') {
      state.page = 'about';
      showPage('about');
      renderAbout();
      document.title = 'About — A.Voss';
    } else if (hash === '#/contact') {
      state.page = 'contact';
      showPage('contact');
      renderContact();
      document.title = 'Contact — A.Voss';
    } else if ((m = hash.match(/^#\/project\/(.+)$/))) {
      state.page = 'detail';
      showPage('detail');
      renderDetail(decodeURIComponent(m[1]));
    } else {
      showPage('404');
      document.title = 'Not found — A.Voss';
    }
  }

  function navigate(hash) {
    if (window.location.hash === hash) { router(); return; }
    window.location.hash = hash;
  }

  /* -------------------- wiring -------------------- */

  function wireStaticUI() {
    document.getElementById('accent-toggle').addEventListener('click', cycleAccent);
    document.getElementById('intro-replay').addEventListener('click', replayIntro);

    document.querySelectorAll('.term-tab').forEach(function (tab) {
      tab.addEventListener('click', function () { navigate('#/' + tab.getAttribute('data-page')); });
    });
    document.querySelectorAll('[data-goto]').forEach(function (el) {
      el.addEventListener('click', function () { navigate('#/' + el.getAttribute('data-goto')); });
    });

    document.getElementById('logo').addEventListener('click', function () { navigate('#/'); });

    document.getElementById('home-grid').addEventListener('click', function () {});
    wireGridDelegation(document.getElementById('home-grid'));
    wireGridDelegation(document.getElementById('work-grid'));

    document.getElementById('work-filters').addEventListener('click', function (e) {
      var btn = e.target.closest('[data-tag]');
      if (!btn) return;
      state.filter = btn.getAttribute('data-tag') || null;
      renderWork();
    });

    document.getElementById('detail-prev').addEventListener('click', function () { stepDetailMedia(-1); });
    document.getElementById('detail-next').addEventListener('click', function () { stepDetailMedia(1); });
    document.getElementById('detail-media-wrap').addEventListener('click', function (e) {
      if (e.target.closest('#detail-prev,#detail-next')) return;
      var p = state.projects.find(function (x) { return x.id === state.activeId; });
      if (!p) return;
      var media = mediaFor(p).filter(function (m) { return m.type !== 'video'; });
      if (!media.length) return;
      openLightbox(p, media, Math.min(state.mediaIndex, media.length - 1));
    });

    document.getElementById('lb-close').addEventListener('click', closeLightbox);
    document.getElementById('lb-prev').addEventListener('click', function () { stepLightbox(-1); });
    document.getElementById('lb-next').addEventListener('click', function () { stepLightbox(1); });
    document.getElementById('lightbox').addEventListener('click', function (e) {
      if (e.target.id === 'lightbox') closeLightbox();
    });
    document.addEventListener('keydown', function (e) {
      var lb = document.getElementById('lightbox');
      if (!lb.classList.contains('open')) return;
      if (e.key === 'Escape') closeLightbox();
      if (e.key === 'ArrowLeft') stepLightbox(-1);
      if (e.key === 'ArrowRight') stepLightbox(1);
    });

    document.getElementById('contact-form').addEventListener('submit', function (e) {
      e.preventDefault();
      var form = e.target;
      var name = form.name.value.trim();
      var email = form.email.value.trim();
      var message = form.message.value.trim();
      var btn = document.getElementById('contact-send');
      if (!name || !email || !message) {
        btn.textContent = './send.sh --error: missing fields';
        setTimeout(function () { btn.textContent = './send.sh'; }, 2200);
        return;
      }
      var subject = encodeURIComponent('Portfolio contact from ' + name);
      var body = encodeURIComponent(message + '\n\n— ' + name + ' (' + email + ')');
      window.location.href = 'mailto:hi@example.dev?subject=' + subject + '&body=' + body;
      btn.textContent = 'sent ✓';
      setTimeout(function () { btn.textContent = './send.sh'; }, 3000);
    });

    window.addEventListener('hashchange', router);
  }

  /* -------------------- boot -------------------- */

  document.addEventListener('DOMContentLoaded', function () {
    applyAccent();
    setupShader();
    wireStaticUI();

    fetchManifest().then(function (manifest) {
      state.projects = manifest.projects || [];
      var ids = sortProjects(state.projects).map(function (p) { return p.id; });
      runIntro(ids, function () {
        document.getElementById('app').style.display = 'block';
        router();
      });
    }).catch(function (err) {
      document.getElementById('intro-overlay').style.display = 'none';
      document.getElementById('intro-vignette').style.display = 'none';
      document.getElementById('app').style.display = 'block';
      document.getElementById('home-grid').innerHTML = '<div class="state-box error">Failed to load projects.json — ' + escapeHtml(err.message) + '</div>';
      document.getElementById('work-grid').innerHTML = document.getElementById('home-grid').innerHTML;
      router();
    });
  });
})();
